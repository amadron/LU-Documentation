"""Build interactive location-map overlays for zones with terrain-bound projections.

Usage (from the documentation root):
    py -3 scripts/build_location_maps.py

The overlays read only the existing coordinate tables. Their projections map
terrain bounds to each minimap and remain provisional until checked against
in-game landmarks.
"""

import html
import json
import math
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
MAP_SIZE = 1024
MAP_CENTER = MAP_SIZE / 2
START = "<!-- location-map:start (generated by scripts/build_location_maps.py) -->"
END = "<!-- location-map:end -->"
ITEM_SECTION = "## Mapped placements and spawner waypoints"
PET_TABLE_HEADER = "| Pet template | X | Y | Z | Scene / spawner | Recorded conditions |"


def zone_config(zone, scale_x, scale_z=None, world_center_x=0.0, world_center_z=0.0):
    if scale_z is None:
        scale_z = scale_x
    return {
        "pixels_per_world_unit_x": scale_x,
        "pixels_per_world_unit_z": scale_z,
        "world_center_x": world_center_x,
        "world_center_z": world_center_z,
        "zone_page": Path(f"wiki/zones/{zone}.md"),
        "item_locations_page": Path(f"wiki/items/locations/zone-{zone}.md"),
        "pet_locations_page": Path(f"wiki/pets/locations/zone-{zone}.md"),
    }


ZONE_CONFIGS = {
    1000: zone_config(1000, 0.5),
    1001: zone_config(1001, 0.5),
    1100: zone_config(1100, 5 / 12),
    1102: zone_config(1102, 5 / 3),
    1150: zone_config(1150, 5 / 3),
    1151: zone_config(1151, 5 / 6, world_center_x=-102.4),
    1200: zone_config(1200, 0.5),
    1201: zone_config(1201, 1.25),
    1204: zone_config(1204, 1.25),
    1250: zone_config(1250, 5 / 3),
    1251: zone_config(1251, 5 / 6, world_center_x=102.4),
    1300: zone_config(1300, 5 / 6),
    1350: zone_config(1350, 5 / 3),
    1400: zone_config(1400, 0.5),
    1402: zone_config(1402, 1.0, 5 / 6),
    1450: zone_config(1450, 5 / 3),
    1600: zone_config(1600, 0.5),
    1700: zone_config(1700, 0.5),
    1800: zone_config(1800, 0.5),
    1900: zone_config(1900, 0.625),
    2000: zone_config(2000, 5 / 12, world_center_x=-204.8),
}

ZONE_LINK = re.compile(r"\]\([^)]*zone-(\d+)\.md\)$")
ITEM_TITLE_SUFFIX = re.compile(r"\s+[—-]\s+source LOT \d+$", re.I)
PET_LINK = re.compile(r"^\[(.*?)\]\(\.\./(\d+)\.md\)$")
SEPARATOR_CELL = re.compile(r"^:?-{3,}:?$")
NUMBER = re.compile(r"^-?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?$")


def read_text(path):
    with open(path, encoding="utf-8", newline="") as file:
        raw = file.read()
    newline = "\r\n" if "\r\n" in raw else "\n"
    return raw.replace("\r\n", "\n"), newline


def write_if_changed(path, text, newline):
    if path.exists():
        old, _ = read_text(path)
        if old == text:
            return False
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as file:
        file.write(text.replace("\n", newline))
    return True


def table_cells(line):
    if not line.startswith("|"):
        return []
    return [cell.strip() for cell in line.strip().strip("|").split("|")]


def is_separator(cells):
    return bool(cells) and all(SEPARATOR_CELL.fullmatch(cell) for cell in cells)


def parse_coordinate(value, path, line_number):
    if not NUMBER.fullmatch(value):
        raise ValueError(f"{path}:{line_number}: invalid map coordinate {value!r}")
    coordinate = float(value)
    if not math.isfinite(coordinate):
        raise ValueError(f"{path}:{line_number}: map coordinate must be finite")
    return coordinate


def coordinates_to_pixel(x, z, zone, path, line_number):
    config = ZONE_CONFIGS[zone]
    pixel_x = MAP_CENTER - (x - config["world_center_x"]) * config["pixels_per_world_unit_x"]
    pixel_y = MAP_CENTER - (z - config["world_center_z"]) * config["pixels_per_world_unit_z"]
    if not (0 <= pixel_x < MAP_SIZE and 0 <= pixel_y < MAP_SIZE):
        raise ValueError(
            f"{path}:{line_number}: XYZ ({x}, {z}) projects outside the zone "
            f"{zone} minimap ({pixel_x:.2f}, {pixel_y:.2f})"
        )
    return round(pixel_x, 3), round(pixel_y, 3)


def item_source_markers(root, zone):
    markers = []
    folder = root / "wiki" / "items" / "sources"
    for path in sorted(folder.glob("object-*.md")):
        lot_match = re.fullmatch(r"object-(\d+)", path.stem)
        if not lot_match:
            continue
        text, _ = read_text(path)
        lines = text.split("\n")
        heading = next((line[2:].strip() for line in lines if line.startswith("# ")), path.stem)
        name = html.unescape(ITEM_TITLE_SUFFIX.sub("", heading))
        in_section = False
        for line_number, line in enumerate(lines, start=1):
            if line.strip() == ITEM_SECTION:
                in_section = True
                continue
            if in_section and line.startswith("## "):
                break
            if not in_section:
                continue
            cells = table_cells(line)
            if len(cells) < 6 or is_separator(cells):
                continue
            zone_match = ZONE_LINK.search(cells[0])
            if not zone_match or int(zone_match.group(1)) != zone:
                continue
            x = parse_coordinate(cells[1], path, line_number)
            y = parse_coordinate(cells[2], path, line_number)
            z = parse_coordinate(cells[3], path, line_number)
            pixel_x, pixel_y = coordinates_to_pixel(x, z, zone, path, line_number)
            markers.append({
                "category": "items",
                "name": name,
                "lot": int(lot_match.group(1)),
                "x": x,
                "y": y,
                "z": z,
                "pixelX": pixel_x,
                "pixelY": pixel_y,
                "details": html.unescape(f"{cells[4]}; {cells[5]}"),
                "path": f"wiki/items/sources/object-{lot_match.group(1)}/",
            })
    return markers


def pet_markers(root, zone):
    path = root / ZONE_CONFIGS[zone]["pet_locations_page"]
    if not path.is_file():
        return []
    text, _ = read_text(path)
    lines = text.split("\n")
    markers = []
    in_table = False
    for line_number, line in enumerate(lines, start=1):
        if line.strip() == PET_TABLE_HEADER:
            in_table = True
            continue
        if in_table and not line.startswith("|"):
            break
        if not in_table:
            continue
        cells = table_cells(line)
        if len(cells) < 6 or is_separator(cells):
            continue
        pet_match = PET_LINK.fullmatch(cells[0])
        if not pet_match:
            continue
        name = html.unescape(re.sub(r"\s+\(\d+\)$", "", pet_match.group(1)))
        lot = int(pet_match.group(2))
        x = parse_coordinate(cells[1], path, line_number)
        y = parse_coordinate(cells[2], path, line_number)
        z = parse_coordinate(cells[3], path, line_number)
        pixel_x, pixel_y = coordinates_to_pixel(x, z, zone, path, line_number)
        markers.append({
            "category": "pets",
            "name": name,
            "lot": lot,
            "x": x,
            "y": y,
            "z": z,
            "pixelX": pixel_x,
            "pixelY": pixel_y,
            "details": html.unescape(f"{cells[4]}; {cells[5]}"),
            "path": f"wiki/pets/{lot}/",
        })
    return markers


def render_block(page, category, zone):
    page_url_depth = len(page.with_suffix("").parts)
    site_root = "../" * page_url_depth
    data_url = f"{site_root}assets/location-maps/{zone}.json"
    image_url = f"{site_root}assets/minimaps/{zone}.webp"
    return "\n".join((
        START,
        "## Location map",
        "",
        "*Location overlay: its terrain-bounds projection is still provisional pending an in-game landmark check. The XYZ coordinates in the source tables remain authoritative.*",
        "",
        f'<div class="lu-location-map" data-location-map data-zone="{zone}" '
        f'data-category="{category}" data-map-data="{data_url}" '
        f'data-map-image="{image_url}" data-site-root="{site_root}">',
        "<p>Interactive map markers are loading. The coordinate tables remain available below.</p>",
        "</div>",
        END,
    ))


def replace_or_insert_block(text, block, page, zone_page):
    start = text.find(START)
    if start >= 0:
        end = text.find(END, start)
        if end < 0:
            raise ValueError(f"{page}: generated location-map block has no end marker")
        end += len(END)
        return text[:start] + block + text[end:]

    if page == zone_page:
        anchor = "<!-- media:end -->"
        position = text.find(anchor)
        if position < 0:
            raise ValueError(f"{page}: minimap media block was not found")
        position += len(anchor)
        return text[:position] + "\n\n" + block + text[position:]

    table_match = re.search(r"(?m)^\|[^\n]*\|\n\|[ :|\\-]+\|$", text)
    if not table_match:
        raise ValueError(f"{page}: location table was not found")
    position = table_match.start()
    return text[:position] + block + "\n\n" + text[position:]


def build(root=ROOT, zone=1100):
    if zone not in ZONE_CONFIGS:
        raise ValueError(f"Unsupported location-map zone: {zone}")
    config = ZONE_CONFIGS[zone]
    map_image = root / "assets" / "minimaps" / f"{zone}.webp"
    if not map_image.is_file():
        raise FileNotFoundError(f"Required zone {zone} minimap not found: {map_image}")

    markers = item_source_markers(root, zone) + pet_markers(root, zone)
    if not markers:
        raise RuntimeError(f"No exact-coordinate locations found for zone {zone}")
    markers.sort(key=lambda marker: (
        marker["category"], marker["name"].casefold(), marker["lot"],
        marker["x"], marker["z"],
    ))

    payload = {
        "zone": zone,
        "projection": {
            "originX": MAP_CENTER,
            "originY": MAP_CENTER,
            "worldCenterX": config["world_center_x"],
            "worldCenterZ": config["world_center_z"],
            "pixelsPerWorldUnit": (
                config["pixels_per_world_unit_x"]
                if config["pixels_per_world_unit_x"] == config["pixels_per_world_unit_z"]
                else None
            ),
            "pixelsPerWorldUnitX": config["pixels_per_world_unit_x"],
            "pixelsPerWorldUnitZ": config["pixels_per_world_unit_z"],
            "xAxisReversed": True,
            "zAxisUp": True,
            "provisional": True,
        },
        "markers": markers,
    }
    data_path = root / "assets" / "location-maps" / f"{zone}.json"
    data_updated = write_if_changed(
        data_path, json.dumps(payload, ensure_ascii=False, indent=2) + "\n", "\n"
    )

    configured_pages = (
        (config["zone_page"], "all"),
        (config["item_locations_page"], "items"),
        (config["pet_locations_page"], "pets"),
    )
    updated_pages = 0
    for relative_path, category in configured_pages:
        page = root / relative_path
        if not page.is_file():
            if relative_path == config["zone_page"]:
                raise FileNotFoundError(f"Required zone page not found: {page}")
            print(f"skip map embed; location page not found: {page}")
            continue
        text, newline = read_text(page)
        updated = replace_or_insert_block(
            text,
            render_block(relative_path, category, zone),
            relative_path,
            config["zone_page"],
        )
        updated_pages += write_if_changed(page, updated, newline)

    return {
        "markers": len(markers),
        "items": sum(marker["category"] == "items" for marker in markers),
        "pets": sum(marker["category"] == "pets" for marker in markers),
        "updated_pages": updated_pages,
        "data_updated": data_updated,
    }


def main():
    for zone in ZONE_CONFIGS:
        stats = build(zone=zone)
        print(
            f"Zone {zone}: {stats['markers']} markers "
            f"({stats['items']} item sources, {stats['pets']} pet placements); "
            f"{stats['updated_pages']} pages updated."
        )


if __name__ == "__main__":
    main()
