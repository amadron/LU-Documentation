def update_faction_guide(classes, data):
    text = FACTION_GUIDE.read_text(encoding="utf-8")
    if MARK_START not in text or MARK_END not in text:
        raise RuntimeError(f"Comparison markers missing in {FACTION_GUIDE}")
    block = "\n".join([MARK_START, ""] + comparison_table(classes, data, "./") + ["", MARK_END])
    start = text.index(MARK_START)
    end = text.index(MARK_END) + len(MARK_END)
    FACTION_GUIDE.write_text(text[:start] + block + text[end:], encoding="utf-8")


def main():
    db_path = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_DB
    locale_path = Path(sys.argv[2]) if len(sys.argv) > 2 else DEFAULT_LOCALE
    data = Data(db_path, locale_path)
    classes = load_classes(data)
    missing = set(classes) - set(PROFILES)
    if missing:
        raise RuntimeError(f"No profile for: {', '.join(sorted(missing))}")
    OUTPUT.mkdir(parents=True, exist_ok=True)
    expected = {"README"} | {c["slug"] for c in classes.values()}
    stale = {p.stem for p in OUTPUT.glob("*.md")} - expected
    if stale:
        raise RuntimeError(f"Obsolete class pages: {', '.join(sorted(stale))}")
    (OUTPUT / "README.md").write_text("\n".join(overview_page(classes, data)), encoding="utf-8")
    for cls in classes.values():
        (OUTPUT / f"{cls['slug']}.md").write_text("\n".join(class_page(cls, classes, data)), encoding="utf-8")
    update_faction_guide(classes, data)
    print(f"Wrote {len(classes)} class pages, wiki/classes/README.md, and the Faction Guide comparison.")


if __name__ == "__main__":
    main()
