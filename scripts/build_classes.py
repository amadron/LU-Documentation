def escape(value):
    text = html.escape(str(value), quote=False).replace("\r", " ").replace("\n", " ")
    return re.sub(r"[\\|`*_\[\]~]", lambda match: f"&#{ord(match.group())};", text)


def slug(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def clean_description(text):
    """Turn client ability text such as '%(DamageCombo) 1+2+3 %(ChargeUp)Blocks 4 attacks' into prose."""
    if not text:
        return ""
    parts = []
    for match in re.finditer(r"%\((\w+)\)([^%]*)", text):
        key, value = match.group(1), match.group(2).strip()
        if not value:
            continue
        if key == "DamageCombo":
            parts.append(f"Damage: {value}.")
        elif key == "AltCombo":
            parts.append(f"Damage vs. Skeletons: {value}.")
        elif key == "ChargeUp":
            parts.append(f"Charge attack: {value.rstrip('.')}.")
        else:
            parts.append(value if value.endswith(".") else f"{value}.")
    if not parts:
        parts.append(text.strip() if text.strip().endswith(".") else f"{text.strip()}.")
    return " ".join(parts)


class Locale:
    def __init__(self, path):
        self.text = path.read_text(encoding="utf-8")
        self.cache = {}

    def get(self, key):
        if key not in self.cache:
            match = re.search(
                r'<phrase id="%s">.*?<translation locale="en_US">(.*?)</translation>' % re.escape(key),
                self.text, re.S)
            self.cache[key] = html.unescape(match.group(1)).strip() if match else None
        return self.cache[key]


class Data:
    def __init__(self, db_path, locale_path):
        self.db = sqlite3.connect(db_path)
        self.loc = Locale(locale_path)
        self.item_pages = {p.stem for p in (ROOT / "wiki" / "items").glob("*.md")}
        self.skill_pages = {p.stem for p in (ROOT / "wiki" / "skills").glob("*.md")}
        self.set_skills = defaultdict(list)
        for set_id, skill in self.db.execute("select SkillSetID, SkillID from ItemSetSkills order by rowid"):
            self.set_skills[set_id].append(skill)

    # --- names and links (relative to wiki/classes/) ---
    def object_name(self, lot):
        row = self.db.execute("select coalesce(nullif(displayName, ''), name) from Objects where id=?",
                              (lot,)).fetchone()
        return row[0].strip() if row and row[0] else f"LOT {lot}"

    def lot_link(self, lot):
        label = f"{escape(self.object_name(lot))} (LOT {lot})"
        return f"[{label}](../items/{lot}.md)" if str(lot) in self.item_pages else label

    def vendor_link(self, lot):
        label = f"{escape(self.object_name(lot))} (LOT {lot})"
        if (ROOT / "wiki" / "items" / "sources" / f"object-{lot}.md").exists():
            return f"[{label}](../items/sources/object-{lot}.md)"
        return label

    def skill_name(self, skill):
        return self.loc.get(f"SkillBehavior_{skill}_name")

    def skill_ref(self, skill):
        name = self.skill_name(skill)
        label = escape(name) if name else f"Skill {skill}"
        if str(skill) in self.skill_pages:
            return f"[{label}](../skills/{skill}.md)"
        return f"{label} ({skill})" if name else label

    def skill_costs(self, skill):
        row = self.db.execute("select imaginationcost, cooldown from SkillBehavior where skillID=?",
                              (skill,)).fetchone()
        cost = row[0] if row and row[0] else None
        cooldown = row[1] if row and row[1] and row[1] > 0 else None
        return cost, cooldown

    def ability(self, skill):
        cost, cooldown = self.skill_costs(skill)
        extras = [f"{cost} IP"] if cost else []
        if cooldown:
            extras.append(f"{cooldown:g} s")
        ref = self.skill_ref(skill)
        return f"{ref} ({', '.join(extras)})" if extras else ref

    # --- missions ---
    def mission_name(self, mission):
        return self.loc.get(f"Missions_{mission}_name") or f"Achievement {mission}"

    def mission_rewards(self, mission):
        row = self.db.execute("select reward_item1, reward_item2, reward_item3, reward_item4 from Missions "
                              "where id=?", (mission,)).fetchone()
        return [lot for lot in (row or ()) if lot and lot > 0]

    def missions_for_skill(self, skill):
        return [r[0] for r in self.db.execute(
            "select id from MissionTasks where taskType=10 and taskParam1=?", (str(skill),))]

    def set_bonus(self, skill):
        desc = self.loc.get(f"SkillBehavior_{skill}_descriptionUI")
        ref = self.skill_ref(skill)
        if desc:
            return f"{ref} — {escape(desc)}"
        missions = self.missions_for_skill(skill)
        if missions:
            parts = []
            for mission in missions:
                rewards = self.mission_rewards(mission)
                reward = (f"rewards {', '.join(self.lot_link(lot) for lot in rewards)}" if rewards
                          else "LEGO Score only")
                parts.append(f"completes achievement *{escape(self.mission_name(mission))}* ({reward})")
            return f"{ref} — full-set trigger: {'; '.join(parts)}"
        return f"{ref} — unnamed effect"

    def rank_book(self, achievement):
        for (mission,) in self.db.execute("select id from Missions"):
            if self.mission_name(mission) != achievement:
                continue
            for (param,) in self.db.execute(
                    "select taskParam1 from MissionTasks where id=? and taskType=10", (mission,)):
                row = self.db.execute("select objectTemplate from ObjectSkills where skillID=? and castOnType=3",
                                      (int(param),)).fetchone()
                if row:
                    return row[0]
        return None

    def kit_package(self, kit):
        row = self.db.execute("select id from Objects where name=?", (f"Rank 1 {kit} Kit Package",)).fetchone()
        return row[0] if row else None

    # --- items ---
    def precondition(self, pre):
        level, achievements = None, []
        for part in filter(None, (p.strip() for p in (pre or "").split(";"))):
            row = self.db.execute("select type, targetLOT from Preconditions where id=?", (int(part),)).fetchone()
            if not row:
                continue
            kind, target = row
            if kind == 22:
                level = int(target)
            elif kind == 4:
                achievements.append(self.mission_name(target))
        return level, achievements

    def item(self, lot):
        row = self.db.execute(
            """select o.name, o.displayName, ic.equipLocation, ic.reqPrecondition,
                      ic.currencyLOT, ic.altCurrencyCost, ic.isTwoHanded
               from Objects o
               left join ComponentsRegistry cr on cr.id=o.id and cr.component_type=11
               left join ItemComponent ic on ic.id=cr.component_id
               where o.id=?""", (lot,)).fetchone()
        if not row:
            return None
        name, display, slot, pre, cur_lot, cur_cost, two_handed = row
        skills = [r[0] for r in self.db.execute(
            "select skillID from ObjectSkills where objectTemplate=? and castOnType=0", (lot,))]
        level, achievements = self.precondition(pre)
        internal = name or ""
        return {
            "lot": lot, "internal": internal, "name": (display or name or f"LOT {lot}").strip(),
            "slot": slot, "level": level, "achievements": achievements, "two_handed": bool(two_handed),
            "cost": cur_cost if cur_lot else None, "skills": skills,
            "variant": "Color Variant" in internal, "proxy": "proxy" in internal.lower(),
            "valiant": (level or 0) > 30,
        }

    def item_link(self, info):
        return self.icon("objects", info["lot"]) + self.lot_link(info["lot"])

    _light = None

    @classmethod
    def icon(cls, kind, ident, width=32):
        """Inline icon from assets/ (written by scripts/build_media.py), if it exists. The icon list
        says which icons are light and need a dark backdrop."""
        if (ROOT / "assets" / "icons" / kind / f"{ident}.webp").exists():
            if cls._light is None:
                try:
                    data = json.loads((ROOT / "assets" / "icons" / "index.json").read_text(encoding="utf-8"))
                    cls._light = {k: set(v) for k, v in data.get("light", {}).items()}
                except (OSError, ValueError):
                    cls._light = {}
            backdrop = "lu-on-dark" if ident in cls._light.get(kind, ()) else "lu-on-light"
            return f'![](../../assets/icons/{kind}/{ident}.webp){{ .lu-ci .{backdrop} width="{width}" }} '
        return ""


def load_classes(data):
    rows = data.db.execute(
        """select setID, itemIDs, kitType, kitRank, skillSetWith2, skillSetWith3, skillSetWith4,
                  skillSetWith5, skillSetWith6, gate_version
           from ItemSets where kitRank between 1 and 3 order by kitType, setID""").fetchall()
    classes = {}
    for row in rows:
        set_id, lots, kit_type, rank = row[:4]
        kit = data.loc.get(f"ItemSets_{set_id}_kitName") or f"Set {set_id}"
        entry = classes.setdefault(kit, {
            "name": kit, "slug": slug(kit), "faction": FACTIONS[kit_type][0], "token": FACTIONS[kit_type][1],
            "later": False, "ranks": {}})
        if row[9] == "factionkit2":
            entry["later"] = True
        items, missing = [], []
        for lot in (int(x) for x in lots.split(",") if x.strip()):
            info = data.item(lot)
            if info is None:
                missing.append(lot)
            elif not info["proxy"]:
                items.append(info)
        items.sort(key=lambda i: (SLOT_ORDER.index(i["slot"]) if i["slot"] in SLOT_ORDER else 99,
                                  i["valiant"], i["variant"], i["lot"]))
        achievement = next((a for i in items for a in i["achievements"]), None)
        entry["ranks"][rank] = {
            "set": set_id, "items": items, "missing": missing, "achievement": achievement,
            "level": min((i["level"] for i in items if i["level"]), default=None),
            "bonuses": dict(zip(range(2, 7), row[4:9])),
            "book": data.rank_book(achievement) if achievement else None,
        }
    return classes


def base_items(rank):
    return [i for i in rank["items"] if not i["variant"]]


def main_weapon(cls):
    for info in cls["ranks"][1]["items"]:
        if info["slot"] == "special_r":
            return info
    return None


def signature(cls, data):
    """Rank-3 neck/back ability: the class's capstone skill."""
    for info in base_items(cls["ranks"][3]):
        if info["slot"] == "clavicle" and info["skills"] and not info["valiant"]:
            return data.skill_ref(info["skills"][0])
    return "—"


def comparison_table(classes, data, link_prefix):
    lines = [
        "| Class | Faction | Role (summary) | Weapon | Rank-1 head ability | Rank-3 signature ability |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for kit_type, (faction, _) in FACTIONS.items():
        for cls in sorted((c for c in classes.values() if c["faction"] == faction), key=lambda c: c["name"]):
            weapon = main_weapon(cls)
            weapon_text = escape(re.sub(r"\s*1$", "", weapon["name"])) if weapon else "—"
            if weapon and weapon["two_handed"]:
                weapon_text += " (two-handed)"
            head = next((i for i in cls["ranks"][1]["items"] if i["slot"] == "hair" and i["skills"]), None)
            head_text = data.skill_ref(head["skills"][0]).replace("](../", f"]({link_prefix}") if head else "—"
            sig = signature(cls, data).replace("](../", f"]({link_prefix}")
            later = " ¹" if cls["later"] else ""
            lines.append(
                f"| [{escape(cls['name'])}]({link_prefix}classes/{cls['slug']}.md){later} | {faction} "
                f"| {PROFILES.get(cls['name'], ('—',))[0]} | {weapon_text} | {head_text} | {sig} |")
    lines += [
        "",
        "¹ Added in a later content update; not covered by the 2010 guide.",
        "",
        "Role summaries are an editorial reading of the ability descriptions in the client data,",
        "not an official classification.",
    ]
    return lines


def class_page(cls, classes, data):
    faction, token = cls["faction"], cls["token"]
    token_name = data.object_name(token)
    role, profile = PROFILES.get(cls["name"], ("—", ""))
    siblings = sorted(c["name"] for c in classes.values() if c["faction"] == faction and c is not cls)
    out = [
        f"# {cls['name']}",
        "",
        "[Classes](./README.md) | [Faction Guide](../Faction%20Guide.md) | "
        + " | ".join(f"[{escape(s)}](./{slug(s)}.md)" for s in siblings),
        "",
        f"**Faction:** {faction} · **Role:** {role} · **Currency:** {escape(token_name)} (LOT {token})",
        "",
        profile,
        "",
    ]
    if cls["later"]:
        out += ["This class was added in a later content update (`factionkit2`) and is not covered by",
                "the 2010 guide. It has no rank-3 color variants.", ""]

    # Abilities by rank
    out += ["## Abilities by rank", "",
            "Abilities come from equipped pieces. Each rank's pieces replace the previous rank's,",
            "so the table shows what a full set of that rank gives you. Descriptions are the client",
            "tooltips.", "",
            "| Rank | Slot | Ability | Effect | IP cost | Cooldown |",
            "| --- | --- | --- | --- | --- | --- |"]
    for rank in (1, 2, 3):
        seen = set()
        for info in base_items(cls["ranks"][rank]):
            for skill in info["skills"]:
                key = (info["slot"], skill)
                if key in seen:
                    continue
                seen.add(key)
                cost, cooldown = data.skill_costs(skill)
                desc = clean_description(data.loc.get(f"SkillBehavior_{skill}_descriptionUI"))
                slot = SLOT_NAMES.get(info["slot"], info["slot"])
                if info["valiant"]:
                    slot += " (valiant)"
                out.append(f"| {rank} | {slot} | {data.icon('skills', skill, 24)}{data.skill_ref(skill)} | {escape(desc) or '—'} "
                           f"| {cost or '—'} | {f'{cooldown:g} s' if cooldown else '—'} |")
    out.append("")

    # Unlocking
    package = data.kit_package(cls["name"])
    ns, nt = VENDORS[faction]
    out += ["## Unlocking the class", ""]
    if package:
        out += [f"1. **Starter kit:** after joining {'the ' if faction == 'Sentinels' else ''}{faction}, choose {data.lot_link(package)} as the reward of",
                f"   *Get your … Gear!* (offered by Nexus Jay). It holds the four rank-1 pieces and the",
                "   rank-1 book. The book is also sold by your Nimbus Station vendor if you start a",
                "   second class later."]
    out += ["2. **Use the class book** for each rank to earn the rank achievement the gear requires.",
            "3. **Wear the full set** of a rank to earn the next rank's book.",
            "4. **Buy the next rank** with faction tokens once you reach its level.", "",
            "| Rank | Level | Required achievement | Class book | How you get the book |",
            "| --- | --- | --- | --- | --- |"]
    for rank in (1, 2, 3):
        r = cls["ranks"][rank]
        how = ("Starter package; Nimbus Station vendor" if rank == 1
               else f"Reward for wearing the full rank-{rank - 1} set")
        out.append(f"| {rank} | {r['level'] or '—'} | *{escape(r['achievement'] or '—')}* "
                   f"| {data.lot_link(r['book']) if r['book'] else '—'} | {how} |")
    out += ["",
            f"**Vendors:** ranks 1–2 at {data.vendor_link(ns)} in Nimbus Station; rank 3, color",
            f"variants, and valiant gear at {data.vendor_link(nt)} in Nexus Tower.", ""]

    # Equipment per rank
    out += ["## Equipment", ""]
    for rank in (1, 2, 3):
        r = cls["ranks"][rank]
        out += [f"### Rank {rank} (set {r['set']})", "",
                "| Slot | Item | Level | Tokens | Item abilities (IP cost, cooldown) |",
                "| --- | --- | --- | --- | --- |"]
        for info in r["items"]:
            note = " (color variant)" if info["variant"] else (" (valiant)" if info["valiant"] else "")
            if info["two_handed"]:
                note += " (two-handed)"
            abilities = ", ".join(data.ability(s) for s in info["skills"]) or "—"
            out.append(f"| {SLOT_NAMES.get(info['slot'], info['slot'] or '—')} | {data.item_link(info)}{note} "
                       f"| {info['level'] or '—'} | {info['cost'] if info['cost'] is not None else '—'} "
                       f"| {abilities} |")
        if r["missing"]:
            out += ["", "Listed in `ItemSets` without an object definition in this database (likely an "
                    "unreleased valiant weapon): " + ", ".join(f"LOT {lot}" for lot in r["missing"]) + "."]
        out += ["", "**Set bonuses** (tiers add up as you equip more pieces of this rank):", ""]
        bonus_lines = [f"- **{count} pieces:** " + "; ".join(data.set_bonus(s) for s in data.set_skills[skill_set])
                       for count, skill_set in r["bonuses"].items() if skill_set]
        out += (bonus_lines or ["- None recorded."]) + [""]

    out += ["## Source and limitations", "",
            "Generated by `scripts/build_classes.py` from the supplied CDServer database and the",
            "English client locale. Values are stored definitions; a particular server can differ.",
            "See [how classes work](./README.md) for vendors, tokens, and server implementation notes.", ""]
    return out


