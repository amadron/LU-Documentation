"""Convert client icons and minimaps to web images and embed them in the documentation pages.

Reads the local LEGO Universe client (DDS textures) and the CDServer database, writes WebP files
under assets/, and inserts an image block (between media markers) into item, skill, pet, and
zone pages. Re-running is safe: images are only re-encoded when missing (use --force), and page
blocks are replaced, not duplicated.

Requires Pillow (local tool only; the site build does not need it):
    .venv\\Scripts\\python -m pip install pillow
    .venv\\Scripts\\python scripts\\build_media.py [--client PATH] [--db PATH] [--force]

Run it after the enrich_*.py scripts, because enrich_zones.py rewrites the zone pages.
"""

import argparse
import math
import os
import re
import sqlite3
from pathlib import Path

from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_CLIENT = ROOT.parent / "client" / "res"
DEFAULT_DB = ROOT.parent / "server" / "resServer" / "CDServer.sqlite"
ASSETS = ROOT / "assets"
START = "<!-- media:start (generated by scripts/build_media.py) -->"
END = "<!-- media:end -->"
EXCLUDED_LOTS = {16900}      # custom development content, not original game data
EXCLUDED_ZONES = {1650}
MINIMAP_ZOOM = "zoom_1"      # 6x6 tiles of 256 px for the large worlds
MINIMAP_MAX = 1024


def resolve(client, path):
    """Client asset paths are relative to a res/ subfolder, e.g. '..\\..\\textures\\ui\\x.dds'."""
    if not path:
        return None
    path = path.replace("\\", "/")
    while path.startswith(("../", "/")):
        path = path[3:] if path.startswith("../") else path[1:]
    candidate = client / path
    return candidate if candidate.is_file() else None


def save_webp(image, target, force):
    if target.exists() and not force:
        return False
    target.parent.mkdir(parents=True, exist_ok=True)
    image.save(target, "WEBP", quality=85, method=6)
    return True


def convert_icon(source, target, force, size=128):
    if target.exists() and not force:
        return True
    try:
        image = Image.open(source).convert("RGBA")
    except Exception as error:  # unsupported or damaged texture
        print(f"skip {source}: {error}")
        return False
    if max(image.size) > size:
        image.thumbnail((size, size), Image.LANCZOS)
    save_webp(image, target, force=True)
    return True


def grid_columns(images):
    """Column count of a row-major tile grid. Square grids are the norm; for other counts pick
    the factorisation whose neighbouring tile edges match best (smallest alpha seam)."""
    count = len(images)
    side = math.isqrt(count)
    if side * side == count:
        return side
    alphas = [image.getchannel("A") for image in images]
    width, height = images[0].size

    def column(alpha, x):
        return alpha.crop((x, 0, x + 1, height)).tobytes()

    def row(alpha, y):
        return alpha.crop((0, y, width, y + 1)).tobytes()

    def seam(cols):
        total = 0
        for index in range(count):
            if index % cols < cols - 1 and index + 1 < count:
                total += sum(abs(a - b) for a, b in zip(column(alphas[index], width - 1), column(alphas[index + 1], 0)))
            if index + cols < count:
                total += sum(abs(a - b) for a, b in zip(row(alphas[index], height - 1), row(alphas[index + cols], 0)))
        return total

    candidates = [c for c in range(2, count) if count % c == 0]
    return min(candidates, key=seam) if candidates else count


def stitch_minimap(folder, target, force):
    if target.exists() and not force:
        return True
    zoom = folder / MINIMAP_ZOOM
    if not zoom.is_dir():
        zoom = folder / "zoom_0"
    tiles = sorted(p for p in zoom.iterdir() if p.suffix.lower() == ".dds")
    if not tiles:
        return False
    images = [Image.open(tile).convert("RGBA") for tile in tiles]
    cols = grid_columns(images)
    rows = len(images) // cols
    tile_w, tile_h = images[0].size
    canvas = Image.new("RGBA", (tile_w * cols, tile_h * rows), (0, 0, 0, 0))
    for index, image in enumerate(images):  # tiles are stored row by row
        canvas.alpha_composite(image, ((index % cols) * tile_w, (index // cols) * tile_h))
    if max(canvas.size) > MINIMAP_MAX:
        canvas.thumbnail((MINIMAP_MAX, MINIMAP_MAX), Image.LANCZOS)
    save_webp(canvas, target, force=True)
    return True


def set_block(page, lines):
    """Insert or replace the media block directly below the page's H1 heading."""
    text = page.read_text(encoding="utf-8")
    newline = "\r\n" if "\r\n" in text else "\n"
    block = newline.join([START, *lines, END])
    if START in text and END in text:
        start = text.index(START)
        end = text.index(END) + len(END)
        updated = text[:start] + block + text[end:]
    else:
        match = re.search(r"^# .*$", text, re.M)
        if not match:
            return False
        insert_at = match.end()
        updated = text[:insert_at] + newline + newline + block + text[insert_at:]
    if updated != text:
        page.write_text(updated, encoding="utf-8", newline="")
        return True
    return False


def remove_block(page):
    text = page.read_text(encoding="utf-8")
    if START not in text:
        return False
    start = text.index(START)
    end = text.index(END) + len(END)
    # also drop the blank line inserted before the block
    while start > 0 and text[start - 1] in "\r\n":
        start -= 1
    page.write_text(text[:start] + text[end:], encoding="utf-8", newline="")
    return True


def object_icon_paths(db):
    icons = dict(db.execute("select IconID, IconPath from Icons"))
    paths = {}
    for lot, asset, icon_id in db.execute(
            """select cr.id, rc.icon_asset, rc.IconID from ComponentsRegistry cr
               join RenderComponent rc on rc.id = cr.component_id where cr.component_type = 2"""):
        path = asset or icons.get(icon_id)
        if path:
            paths[lot] = path
    return paths, icons


def page_ids(folder):
    return sorted(int(p.stem) for p in folder.glob("*.md") if p.stem.isdigit())


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--client", type=Path, default=DEFAULT_CLIENT)
    parser.add_argument("--db", type=Path, default=DEFAULT_DB)
    parser.add_argument("--force", action="store_true", help="re-encode existing images")
    args = parser.parse_args()
    db = sqlite3.connect(args.db)
    object_icons, icon_table = object_icon_paths(db)
    stats = {}

    def embed(kind, folder, ids, source_for, asset_dir, alt_for, width):
        done = changed = 0
        for page_id in ids:
            page = folder / f"{page_id}.md"
            source = None if page_id in EXCLUDED_LOTS else source_for(page_id)
            target = ASSETS / asset_dir / f"{page_id}.webp"
            if source and convert_icon(source, target, args.force):
                rel = os.path.relpath(target, folder).replace(os.sep, "/")
                line = f'![{alt_for(page_id)}]({rel}){{ width="{width}" loading="lazy" }}'
                changed += set_block(page, [line])
                done += 1
            else:
                changed += remove_block(page)
        stats[kind] = (done, len(ids), changed)

    def first_heading(page):
        match = re.search(r"^# (.*)$", page.read_text(encoding="utf-8"), re.M)
        return re.sub(r"[\[\]]", "", match.group(1)).strip() if match else ""

    # Items and pets: the object's inventory icon.
    for kind, folder in (("items", ROOT / "wiki" / "items"), ("pets", ROOT / "wiki" / "pets")):
        embed(kind, folder, page_ids(folder),
              lambda lot: resolve(args.client, object_icons.get(lot)),
              "icons/objects",
              lambda lot, f=folder: f"{first_heading(f / f'{lot}.md')} icon",
              64)

    # Skills: SkillBehavior.skillIcon -> Icons.
    skill_icons = dict(db.execute("select skillID, skillIcon from SkillBehavior"))
    skills = ROOT / "wiki" / "skills"
    embed("skills", skills, page_ids(skills),
          lambda skill: resolve(args.client, icon_table.get(skill_icons.get(skill))),
          "icons/skills",
          lambda skill: f"{first_heading(skills / f'{skill}.md')} icon",
          48)

    # Zones: minimap tiles under maps/minimaps/<luz name>/.
    zones = ROOT / "wiki" / "zones"
    zone_names = dict(db.execute("select zoneID, zoneName from ZoneTable"))
    minimaps = args.client / "maps" / "minimaps"
    done = changed = 0
    zone_ids = [z for z in page_ids(zones) if z not in EXCLUDED_ZONES]
    for zone in zone_ids:
        page = zones / f"{zone}.md"
        luz = zone_names.get(zone)
        folder = minimaps / Path(luz.replace("\\", "/")).stem.lower() if luz else None
        target = ASSETS / "minimaps" / f"{zone}.webp"
        if folder and folder.is_dir() and stitch_minimap(folder, target, args.force):
            rel = os.path.relpath(target, zones).replace(os.sep, "/")
            name = first_heading(page)
            changed += set_block(page, [
                f'![Minimap of {name}]({rel}){{ width="480" loading="lazy" }}',
                "",
                "*In-game minimap from the client (stitched from the minimap tiles).*",
            ])
            done += 1
        else:
            changed += remove_block(page)
    stats["zones (minimaps)"] = (done, len(zone_ids), changed)

    for kind, (done, total, changed) in stats.items():
        print(f"{kind}: {done} of {total} pages have an image; {changed} pages updated")

    pages, icons = add_table_icons()
    print(f"tables: {icons} icons in {pages} updated pages")


TABLE_ICON = re.compile(r'!\[\]\([^)\s]*assets/icons/[^)\s]*\)\{ \.lu-ti[^}]*\} ')
LINK = re.compile(r'(?<!!)\[[^\]\n]*\]\(([^)\s#]+\.md)(?:#[^)\s]*)?\)')
TABLE_SKIP = {"classes"}  # class pages get their icons from scripts/build_classes.py


def add_table_icons():
    """Put a small icon before every table link that points to an item, pet, or skill page."""
    wiki = ROOT / "wiki"
    targets = {"items": "objects", "pets": "objects", "skills": "icons_skills"}
    changed_pages = icon_count = 0
    for page in wiki.rglob("*.md"):
        if page.relative_to(wiki).parts[0] in TABLE_SKIP:
            continue
        text = page.read_text(encoding="utf-8")
        lines = text.split("\n")
        updated = False
        for index, line in enumerate(lines):
            if not line.lstrip().startswith("|"):
                continue
            clean = TABLE_ICON.sub("", line)
            seen = set()  # one icon per target and row (ID and name columns often link the same page)

            def add_icon(match):
                nonlocal icon_count
                target = (page.parent / match.group(1)).resolve()
                try:
                    folder, name = target.relative_to(wiki).parts
                except ValueError:
                    return match.group(0)
                if folder not in targets or not name[:-3].isdigit():
                    return match.group(0)
                kind = "skills" if folder == "skills" else "objects"
                icon = ASSETS / "icons" / kind / f"{name[:-3]}.webp"
                if not icon.exists() or icon in seen:
                    return match.group(0)
                seen.add(icon)
                rel = os.path.relpath(icon, page.parent).replace(os.sep, "/")
                icon_count += 1
                return f'![]({rel}){{ .lu-ti width="24" loading="lazy" }} ' + match.group(0)

            new = LINK.sub(add_icon, clean)
            if new != line:
                lines[index] = new
                updated = True
        if updated:
            page.write_text("\n".join(lines), encoding="utf-8", newline="")
            changed_pages += 1
    return changed_pages, icon_count


if __name__ == "__main__":
    main()
